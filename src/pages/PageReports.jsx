import { useState, useMemo } from "react";
import { Icon, Icons } from "../icons/Icons.jsx";
import PageHeader from "../components/PageHeader.jsx";
import DataState from "../components/DataState.jsx";
import { api, useApi, formatDate } from "../utils/api.js";

// The head manager's view of ops.generated_reports — every credit memo, risk report, fraud
// report and policy exception generated for any application. (An officer sees their own on
// OfficerReports.) With no reports the page says so; nothing here is a placeholder.
const TYPE_LABEL = { credit_memo: "Credit Memo", risk_report: "Risk Report", fraud_report: "Fraud Report", policy_exception: "Policy Exception" };
const TYPE_BADGE = { credit_memo: "badge-blue", risk_report: "badge-amber", fraud_report: "badge-red", policy_exception: "badge-purple" };
const STATUS_LABEL = { draft: "Draft", generated: "Generated", reviewed: "Reviewed", sent_to_manager: "Sent to Manager" };
const STATUS_BADGE = { draft: "badge-gray", generated: "badge-blue", reviewed: "badge-green", sent_to_manager: "badge-amber" };
const TABS = ["All", "credit_memo", "risk_report", "fraud_report", "policy_exception"];

export default function PageReports({ setPage, openApp }) {
  const [tab, setTab] = useState("All");
  const { data, loading, error, reload } = useApi(() => api.reports(), []);
  const reports = data?.reports ?? [];
  const shown = useMemo(() => (tab === "All" ? reports : reports.filter(r => r.report_type === tab)), [reports, tab]);
  const count = s => reports.filter(r => r.status === s).length;
  const open = r => { openApp?.(r.application_no); setPage("app-detail"); };

  return (
    <div>
      <PageHeader title="Reports & Credit Memos" sub="Credit memos, risk reports, fraud reports and policy exceptions across all applications" />

      <div className="grid4" style={{ marginBottom: 16 }}>
        {[
          { label: "Total Reports", value: reports.length, color: "var(--blue)" },
          { label: "Draft", value: count("draft"), color: "var(--text2)" },
          { label: "Generated", value: count("generated"), color: "var(--green)" },
          { label: "Sent to Manager", value: count("sent_to_manager"), color: "var(--amber)" },
        ].map(s => (
          <div key={s.label} className="stat-card" style={{ padding: "12px 14px" }}>
            <div className="stat-label">{s.label}</div>
            <div style={{ fontFamily: "var(--font-sans)", fontSize: 24, fontWeight: 700, color: s.color }}>{s.value}</div>
          </div>
        ))}
      </div>

      <div className="card" style={{ marginBottom: 16 }}>
        <div style={{ display: "flex", gap: 2, background: "var(--surface2)", borderRadius: 8, padding: 3, flexWrap: "wrap" }}>
          {TABS.map(t => <div key={t} className={`tab ${tab === t ? "active" : ""}`} onClick={() => setTab(t)}>{t === "All" ? "All" : TYPE_LABEL[t]}</div>)}
        </div>
      </div>

      <DataState
        loading={loading} error={error} onRetry={reload}
        empty={shown.length === 0} label="reports"
        emptyIcon={Icons.report}
        emptyTitle={reports.length === 0 ? "No reports yet" : "No reports of this type"}
        emptySub={reports.length === 0
          ? "Credit memos and reports appear here once they are generated from an application."
          : "Try another tab."}
      >
        <div className="card">
          <div className="card-title" style={{ marginBottom: 14 }}>All Reports</div>
          <div className="table-wrap">
            <table>
              <thead><tr><th>Report ID</th><th>Application</th><th>Type</th><th>Generated By</th><th>Generated</th><th>Status</th><th>Actions</th></tr></thead>
              <tbody>
                {shown.map(r => (
                  <tr key={r.report_no}>
                    <td style={{ fontFamily: "var(--font-mono)", fontSize: 11, color: "var(--blue)", fontWeight: 600 }}>{r.report_no}</td>
                    <td>
                      <span className="bold" style={{ fontSize: 12 }}>{r.customer_name}</span><br />
                      <span style={{ fontSize: 10, color: "var(--text3)", fontFamily: "var(--font-mono)" }}>{r.application_no}</span>
                    </td>
                    <td><span className={`badge ${TYPE_BADGE[r.report_type] || "badge-gray"}`} style={{ fontSize: 10 }}>{TYPE_LABEL[r.report_type] || r.report_type}</span></td>
                    <td style={{ fontSize: 12, color: "var(--text2)" }}>{r.generated_by_name || "System"}</td>
                    <td style={{ fontSize: 11, color: "var(--text3)", fontFamily: "var(--font-mono)" }}>{formatDate(r.generated_at)}</td>
                    <td><span className={`badge ${STATUS_BADGE[r.status] || "badge-gray"}`} style={{ fontSize: 10 }}>{STATUS_LABEL[r.status] || r.status}</span></td>
                    <td><button className="btn btn-ghost" style={{ fontSize: 11, padding: "4px 8px" }} onClick={() => open(r)}><Icon d={Icons.eye} size={11} /> Preview</button></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      </DataState>
    </div>
  );
}
